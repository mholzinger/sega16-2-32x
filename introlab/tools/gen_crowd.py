#!/usr/bin/env python3
"""The launcher's crowd: the murmur of a room of people, made from the game's own speech.

    gen_crowd.py SPEECH_DIR OUT.h [--wav PREVIEW.wav] [--seconds 5] [--level 122]

SPEECH_DIR holds the arcade's spoken phrases as WAVs (utt_*.wav, decoded from the owner's
rom set by the sound lab; never tracked). Without them the output is an empty loop and
the room has no crowd.

The recipe Mike chose by ear (2026-11-14, "g9"): 32 voices, each a run of short pieces of
the phrases, 100-240 ms, played BACKWARDS under a rounded window, overlapping by half, each
voice a little faster or slower than the others, everything above 1600 Hz taken off. Laid
around a circle so the end joins the start. Then, because a murmur is not constant, its
level waves in and out: two slow swells of different length, never fully away.

Output: 16-bit words for the 32X's PWM register, centred on 512, at 5618 samples a second:
a quarter of the rate the player runs the PWM at (a 1024-clock period), which draws the
three samples in between itself (sh/crowd.c). The loop starts at its quietest
point, which is where the player's restart lands. Level 122 of 512 (Mike on the rig,
2026-11-14: 200, then 10%, 20% and 15% off)."""
import glob, math, os, random, sys, wave
import numpy as np

RATE_IN = 8000
RATE_OUT = 23011361.0 / 1024 / 4
def arg(name, default):
    return type(default)(sys.argv[sys.argv.index(name) + 1]) if name in sys.argv else default

def phrases(src):
    out = []
    for p in sorted(glob.glob(os.path.join(src, 'utt_*.wav'))):
        w = wave.open(p); sr = w.getframerate()
        a = np.frombuffer(w.readframes(w.getnframes()), '<i2' if w.getsampwidth() == 2 else 'u1').astype(float)
        if w.getsampwidth() == 1: a = (a - 128) * 256
        if w.getnchannels() == 2: a = a.reshape(-1, 2).mean(axis=1)
        if len(a) < sr * 0.25: continue
        out.append(np.interp(np.arange(0, len(a), sr / RATE_IN), np.arange(len(a)), a))
    return out

def crowd(utts, secs, seed=14, voices=32, piece_ms=(100, 240), spread=0.28, top=1600):
    r = random.Random(seed); n = int(RATE_IN * secs); mix = np.zeros(n)
    for _ in range(voices):
        pos = r.randint(0, n - 1); speed = 1 + r.uniform(-spread, spread); done = 0
        while done < n:
            u = r.choice(utts); g = int(RATE_IN * r.uniform(*piece_ms) / 1000.0); need = int(g * speed) + 2
            if len(u) <= need: continue
            s = r.randint(0, len(u) - need)
            piece = np.interp(np.arange(g) * speed, np.arange(need), u[s:s + need][::-1]) * np.hanning(g) * r.uniform(0.5, 1.0)
            np.add.at(mix, (pos + np.arange(g)) % n, piece)
            step = int(g * 0.55) + int(RATE_IN * r.uniform(0, 0.08)); pos = (pos + step) % n; done += step
    F = np.fft.rfft(mix); f = np.fft.rfftfreq(n, 1.0 / RATE_IN)
    F[f > top] *= np.exp(-((f[f > top] - top) / 300.0) ** 2); F[f < 150] = 0
    return np.fft.irfft(F, n)

def swell(n, depth):
    """the level around the loop: 1 at its fullest, 1 - depth at its quietest, which is at the join"""
    t = np.arange(n) / float(n)
    w = 0.62 * np.cos(2 * math.pi * t) + 0.38 * np.cos(2 * math.pi * (2 * t + 0.19))     # two swells a loop, unequal
    w = (w - w.min()) / (w.max() - w.min())
    g = (1 - depth) + depth * (1 - w)
    return np.roll(g, -int(np.argmin(g)))

def main():
    src, out = sys.argv[1], sys.argv[2]
    secs, level, depth = arg('--seconds', 5.0), arg('--level', 122), arg('--depth', 0.7)
    utts = phrases(src)
    if not utts:
        open(out, 'w').write('/* generated by tools/gen_crowd.py: no speech was found, so no crowd. */\n#define CROWD_WORDS 0\nstatic const uint16_t crowd_loop[1] = { 512 };\n')
        print('crowd: no phrases in %s, the room has no crowd' % src); return
    x = crowd(utts, secs)
    n = int(round(RATE_OUT * secs))
    y = np.interp(np.arange(n) * (len(x) / float(n)), np.arange(len(x) + 1), np.append(x, x[0]))
    y = y / np.sqrt((y ** 2).mean())                         # unit loudness before the swell
    y = y * swell(n, depth)
    y = y / np.abs(y).max()
    pwm = np.clip(np.round(512 + y * level), 1, 1023).astype(int)
    with open(out, 'w') as f:
        f.write('/* generated by tools/gen_crowd.py from the arcade speech. Do not edit. */\n#define CROWD_WORDS %d\n' % n)
        f.write('static const uint16_t crowd_loop[CROWD_WORDS] __attribute__((aligned(4))) = {\n')
        for i in range(0, n, 20): f.write('\t' + ','.join(str(v) for v in pwm[i:i + 20]) + ',\n')
        f.write('};\n')
    print('crowd: %.1f s, %d words (%d B), level +-%d of 512, swell depth %.2f' % (secs, n, 2 * n, level, depth))
    if '--wav' in sys.argv:
        w = wave.open(arg('--wav', ''), 'wb'); w.setnchannels(1); w.setsampwidth(2); w.setframerate(int(round(RATE_OUT)))
        w.writeframes(np.tile(((pwm - 512) * 64).astype('<i2'), 3).tobytes()); w.close()

if __name__ == '__main__':
    main()
