#!/usr/bin/env python3
"""Pack the intro doors into the header the rom compiles in.

    pack_doors.py   -> art/logo/doors_data.h  (needs art/logo/logo.json; see build_logo.py)

The geometry is doors_preview.py's, so the preview shows what is packed. A vertex is stored
in its own door's frame: r = distance from the hinge (0 at the screen edge, 1 at the seam)
and y, both as int16 with 4096 = one door width. Left-door vertices come first."""
import json
import os

import doors_preview as dp

UNIT = 4096


def main():
    logo = json.load(open(os.path.join(dp.OUT, "logo.json")))
    kinds = {"panel": 1, "frame": 2, "under": 3}
    kinds.update({f"band{b}": 4 + b for b in range(dp.BANDS)})
    verts, polys, nv_left = [], [], 0
    for side in (-1, 1):
        index = {}
        for kind, poly in dp.door_polys(side, logo):
            vi = []
            for x, y in poly:
                r = (x + 1.0) if side < 0 else (1.0 - x)
                key = (int(round(r * UNIT)), int(round(y * UNIT)))
                if key not in index:
                    index[key] = len(verts)
                    verts.append(key)
                vi.append(index[key])
            polys.append((len(vi), kinds[kind], vi + [0] * (4 - len(vi))))
        if side < 0:
            nv_left = len(verts)
    if len(verts) > 65535:
        raise SystemExit("pack_doors: too many vertices for uint16 indices")
    h = ["/* Generated by introlab/tools/logo/pack_doors.py. Do not edit, do not commit. */",
         "#ifndef DOORS_DATA_H", "#define DOORS_DATA_H", "#include <stdint.h>", "",
         f"#define DOORS_NVERTS  {len(verts)}",
         f"#define DOORS_NV_LEFT {nv_left}       /* vertices below this index belong to the left door */",
         f"#define DOORS_NPOLYS  {len(polys)}",
         f"#define DOORS_UNIT    {UNIT}      /* one door width */",
         f"#define DOORS_DIST    {int(round(dp.DIST * UNIT))}      /* camera to the closed doors */",
         f"#define DOORS_FOCAL_PX {dp.FOCAL_PX}",
         "#define DOORS_PANEL   1         /* a polygon's kind is its CRAM entry */",
         "#define DOORS_FRAME   2", "#define DOORS_UNDER   3         /* the pale underlay: outline, hairline, gaps */",
         "#define DOORS_BAND0   4         /* the logo's fill, top band first */",
         f"#define DOORS_BANDS   {dp.BANDS}", f"#define DOORS_NCRAM   {4 + dp.BANDS}", "",
         "/* {r, y}: distance from the hinge and height, DOORS_UNIT = one door width, y up. */",
         "static const int16_t doors_verts[DOORS_NVERTS][2] = {"]
    h += ["\t" + ",".join(f"{{{r},{y}}}" for r, y in verts[i:i + 8]) + "," for i in range(0, len(verts), 8)]
    h += ["};", "", "typedef struct { uint8_t nv, kind; uint16_t vi[4]; } doors_poly_t;", "",
          "/* Back to front within each door: panel, frame, logo. */",
          "static const doors_poly_t doors_polys[DOORS_NPOLYS] = {"]
    h += [f"\t{{{nv},{k},{{{','.join(map(str, vi))}}}}}," for nv, k, vi in polys]
    h += ["};", "", "/* Full-light colours by CRAM entry, 0-31 per channel: room, panel, frame, underlay, bands. */",
          "static const uint8_t doors_rgb[DOORS_NCRAM][3] = {"]
    sch = dp.SCHEMES[dp.CHOSEN]
    cols = [sch["room"], sch["panel"], sch["frame"], sch["under"]] + [dp.colour_of(sch, f"band{b}") for b in range(dp.BANDS)]
    h += ["\t{" + ",".join(str(int(c) >> 3) for c in col) + "}," for col in cols]
    h += ["};", "", "#endif", ""]
    path = os.path.join(dp.OUT, "doors_data.h")
    open(path, "w").write("\n".join(h))
    print(f"packed doors: {len(polys)} polygons, {len(verts)} vertices ({nv_left} left) -> {path}")


if __name__ == "__main__":
    main()
