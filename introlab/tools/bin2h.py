#!/usr/bin/env python3
"""bin2h.py NAME OUT.h FILE...: the files, end to end, as one array of bytes aligned for
68K word reads."""
import sys
data = b"".join(open(f, "rb").read() for f in sys.argv[3:])
out = ["/* generated by tools/bin2h.py. Do not edit. */",
       "const unsigned char %s[%d] __attribute__((aligned(4))) = {" % (sys.argv[1], len(data))]
out += ["\t" + ",".join(str(b) for b in data[i:i + 32]) + "," for i in range(0, len(data), 32)]
open(sys.argv[2], "w").write("\n".join(out + ["};", ""]))
