#!/usr/bin/env python3
"""The launcher's smoke layer: original art, generated from a seed (2026-11-14).

    introlab/tools/gen_wisps.py OUT.png [--preview SCREEN.png OUT.gif]
    introlab/tools/gen_wisps.py --header sh/smoke_data.h md/smoke_sine.h

A 512x256 picture that wraps in x: three shades (pixel values 1..3) over transparent (0),
confined to screen lines TOP..BOT, the band behind the cabinet that Mike marked. Streaks sit
on every other row and every other pixel, so coverage stays near 10% and the wall reads
through. The motion is not in the art: each line from 112 down is shifted sideways by
7.3 * sin(2*pi*(frame/128 + line/128)), the wave measured on a commercial Mega Drive title's
fog room (static plane, per-line horizontal scroll). No pixel here comes from that title.
"""
import math, os, sys
import numpy as np
from PIL import Image
W, H = 512, 256
SHADES = {1: (74, 84, 134), 2: (104, 116, 164), 3: (140, 152, 196)}

def make(seed=11, top=110, bot=184, n=28):
    r=np.random.default_rng(seed); d=np.zeros((H,W))
    yy,xx=np.mgrid[0:H,0:W]
    for _ in range(n):                       # clouds: a few lobes each, wide and flat
        cy=top+8+(bot-top-14)*r.random()**0.65    # most of them low in the band
        cx=r.random()*W
        for k in range(4):
            ox=cx+(r.random()-0.5)*90; oy=cy+(r.random()-0.5)*10
            rx=18+r.random()*38; ry=2+r.random()*4; a=0.6+0.5*r.random()
            dx=np.minimum(abs(xx-ox),W-abs(xx-ox))
            d+=a*np.exp(-(dx/rx)**2-((yy-oy)/ry)**2)
    low=np.clip((yy-top)/float(bot-top),0,1)                   # 0 at the top limit, 1 at the bottom
    edge=np.clip(np.minimum((yy-top)/10.0,(bot-yy)/4.0),0,1)   # long fade in above, short one below
    d=d*edge
    rw=r.random(H); roww=np.where(rw>0.45,1.0,0.35)[:,None]   # streak rows vs gaps
    jit=r.random((H,W))
    v=d*roww*(0.75+0.5*jit)
    dot=(xx+yy)%2==0
    on=(v>0.66-0.28*low)&dot&(yy%2==0)        # every other row, every other pixel: 25% at most
    on|=(v>1.5-0.5*low)&dot                   # cores reach 50%, sooner near the bottom
    on|=(jit<0.10*low**3*edge)&dot            # a thin haze that only exists in the lowest lines
    on[(yy<top)|(yy>bot)]=False
    shade=np.where(d>1.8,3,np.where(d>1.0,2,1))
    return np.where(on,shade,0).astype(np.uint8)

def shift(frame, y):
    return int(round(7.3 * math.sin(2 * math.pi * (frame / 128.0 + y / 128.0)))) if y >= 112 else 0

def headers(layer, sh_path, md_path):
    """The layer as Mega Drive tiles (4 bits a pixel, shared when identical) and a 64-wide map
    of the tile rows the band touches; and the wave as one signed shift per phase step."""
    r0, r1 = min(y for y in range(H) if layer[y].any()) // 8, max(y for y in range(H) if layer[y].any()) // 8
    tiles, index, cells = [], {}, []
    for ty in range(r0, r1 + 1):
        for tx in range(W // 8):
            t = layer[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8]
            if not t.any(): cells.append(0); continue
            k = t.tobytes()
            if k not in index:
                index[k] = len(tiles) + 1
                tiles.append([sum(int(t[y, x * 4 + i]) << (12 - 4 * i) for i in range(4)) for y in range(8) for x in range(2)])
            cells.append(index[k])
    md = lambda c: (round(c[2] / 36.4) << 9) | (round(c[1] / 36.4) << 5) | (round(c[0] / 36.4) << 1)
    with open(sh_path, 'w') as f:
        f.write('/* generated by tools/gen_wisps.py: the smoke layer as Mega Drive tiles. Do not edit. */\n')
        f.write('#define SMOKE_NTILES %d\n#define SMOKE_ROW0 %d\n#define SMOKE_ROWS %d\n' % (len(tiles), r0, r1 - r0 + 1))
        f.write('static const uint16_t smoke_shades[3] = { %s };   /* MD colour words, dim to bright */\n' % ', '.join('0x%04X' % md(SHADES[i]) for i in (1, 2, 3)))
        f.write('static const uint16_t smoke_tiles[SMOKE_NTILES * 16] = {\n')
        for t in tiles: f.write('\t' + ','.join('0x%04X' % w for w in t) + ',\n')
        f.write('};\n/* 0 is an empty cell, otherwise 1 + the tile\'s number */\nstatic const uint16_t smoke_map[SMOKE_ROWS * 64] = {\n')
        for r in range(r1 - r0 + 1): f.write('\t' + ','.join(str(c) for c in cells[r * 64:r * 64 + 64]) + ',\n')
        f.write('};\n')
        f.write('static const int8_t smoke_wave[128] = { %s };\n' % ', '.join(str(int(round(7.3 * math.sin(2 * math.pi * i / 128.0)))) for i in range(128)))
    # the same picture as words for the port's 68K program (md/smoke68k.c), which it follows in the page
    wave = [int(round(7.3 * math.sin(2 * math.pi * i / 128.0))) & 0xFF for i in range(128)]
    # a tile row there is ONE word, two bits a pixel (the shades are 1..3): half the bytes, and the
    # 68K spreads each pixel back to four bits as it uploads
    two = lambda hi, lo: sum((((hi << 16 | lo) >> (28 - 4 * i)) & 3) << (14 - 2 * i) for i in range(8))
    pic = [0x5350, len(tiles), r0, r1 - r0 + 1] + [md(SHADES[i]) for i in (1, 2, 3)]
    pic += [(wave[i] << 8) | wave[i + 1] for i in range(0, 128, 2)] + [two(t[2 * r], t[2 * r + 1]) for t in tiles for r in range(8)] + cells
    with open(os.path.splitext(sh_path)[0] + '.pic', 'wb') as f:
        f.write(b''.join(w.to_bytes(2, 'big') for w in pic))
    with open(md_path, 'w') as f:
        f.write('/* generated by tools/gen_wisps.py: the smoke wave, 7.3 px, one cycle in 128 steps. Do not edit. */\n')
        f.write('static const int16_t smoke_sine[128] = { %s };\n' % ', '.join(str(int(round(7.3 * math.sin(2 * math.pi * i / 128.0)))) for i in range(128)))
    assert len(tiles) <= 512, 'VRAM 0x4000-0x7FFF holds 512 tiles'
    print('smoke: %d tiles, tile rows %d..%d' % (len(tiles), r0, r1))

def main():
    layer = make()
    if sys.argv[1] == '--header':
        return headers(layer, sys.argv[2], sys.argv[3])
    im = Image.fromarray(layer, 'P')
    im.putpalette([0, 0, 0] + sum((list(SHADES[i]) for i in (1, 2, 3)), []) + [0] * (252 * 3))
    im.save(sys.argv[1], transparency=0)
    print('coverage % per 16 lines', [round((layer[y:y + 16] > 0).mean() * 100) for y in range(0, 224, 16)])
    if '--preview' in sys.argv:
        i = sys.argv.index('--preview')
        bg = Image.open(sys.argv[i + 1]).convert('RGB').crop((0, 0, 320, 224))
        frames = []
        for t in range(0, 128, 4):
            f = bg.copy(); px = f.load()
            for y in range(224):
                s = shift(t, y)
                for x in range(320):
                    q = layer[y, (x - s) % W]
                    if q: px[x, y] = SHADES[q]
            frames.append(f.resize((640, 448), Image.NEAREST))
        frames[0].save(sys.argv[i + 2], save_all=True, append_images=frames[1:], duration=67, loop=0)

if __name__ == '__main__':
    main()
