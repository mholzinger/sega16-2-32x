#!/usr/bin/env python3
"""Writes sh/font8.h from md/font.s: the lab's 8x8 font as one bit per pixel, for text drawn
into the 32X page (sh/text.c).  usage: gen_font.py md/font.s sh/font8.h"""
import re, sys
longs = [int(v, 16) for v in re.findall(r'\.long\s+0x([0-9A-Fa-f]{8})', open(sys.argv[1]).read())]
assert len(longs) % 8 == 0, "font.s: a glyph is eight .long rows"
rows = [sum(1 << (7 - k) for k in range(8) if (v >> (28 - 4 * k)) & 15) for v in longs]
n = len(rows) // 8
out = ["/* Generated by introlab/tools/gen_font.py from md/font.s. Do not edit. */",
       "#ifndef FONT8_H", "#define FONT8_H", "#include <stdint.h>", f"#define FONT8_N {n}",
       "static const uint8_t font8[FONT8_N][8] = {"]
out += ["\t{" + ",".join("0x%02X" % r for r in rows[8 * g:8 * g + 8]) + "}," for g in range(n)]
out += ["};", "#endif", ""]
open(sys.argv[2], "w").write("\n".join(out))
