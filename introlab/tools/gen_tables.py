#!/usr/bin/env python3
"""Writes sh/gen_tables.h: the lookup tables the SH-2 renderer needs and cannot compute
without a maths library.  usage: gen_tables.py <out.h>"""
import math
import sys

ANGLES = 1024          # steps per full turn
lines = ["/* Generated by introlab/tools/gen_tables.py. Do not edit. */",
         "#ifndef GEN_TABLES_H", "#define GEN_TABLES_H", "#include <stdint.h>", "",
         f"#define ANGLE_STEPS {ANGLES}",
         "/* sin in 2.14 fixed point; cos(a) = sin(a + ANGLE_STEPS / 4). */",
         f"static const int16_t sin_tab[{ANGLES}] = {{"]
vals = [round(math.sin(2 * math.pi * i / ANGLES) * 16384) for i in range(ANGLES)]
lines += ["\t" + ",".join(str(v) for v in vals[i:i + 16]) + "," for i in range(0, ANGLES, 16)]
lines += ["};", "", "/* recip_tab[n] = 65536 / n, for span lengths 1..320 (entry 0 unused). */",
          "static const uint32_t recip_tab[321] = {"]
rec = [0] + [65536 // n for n in range(1, 321)]
lines += ["\t" + ",".join(str(v) for v in rec[i:i + 16]) + "," for i in range(0, 321, 16)]
lines += ["};", "", "/* ellipse_tab[i] = 256 * sqrt(1 - (i/32)^2): half-width of an ellipse row, i = 0 at its middle. */",
          "static const uint16_t ellipse_tab[33] = {",
          "\t" + ",".join(str(round(256 * math.sqrt(max(0.0, 1 - (i / 32) ** 2)))) for i in range(33)) + ",",
          ]
lines += ["};", "", "#endif", ""]
open(sys.argv[1], "w").write("\n".join(lines))
