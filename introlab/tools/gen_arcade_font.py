#!/usr/bin/env python3
"""Writes art/<title>/font_arcade.h: the game's own 8x8 text letters, read from the owner's
arcade rom set, for the words the launcher draws into the 32X page (sh/text.c).

    gen_arcade_font.py titles/altbeast.json art/altbeast/font_arcade.h

64 glyphs, ASCII 32..95. Each row is two bytes: the face's pixels, then the shadow's. The
output is derived from Sega artwork and lands in the untracked art folder."""
import json, os, sys, zipfile
cfg = json.load(open(sys.argv[1]))["font"]
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.normpath(os.path.join(here, "..", ".."))
z = os.path.join(root, cfg["zip"])
planes = [zipfile.ZipFile(z).read(n) for n in cfg["planes"]]
rows = []
for g in range(64):
    t = cfg["first_tile"] + g
    face, shade = [], []
    for y in range(8):
        px = [sum(((planes[k][t * 8 + y] >> (7 - x)) & 1) << k for k in range(3)) for x in range(8)]
        # letters use 1 and 2 only; the few symbol tiles with more tones fold onto the two
        face.append(sum(1 << (7 - x) for x in range(8) if px[x] & 1))
        shade.append(sum(1 << (7 - x) for x in range(8) if px[x] and not px[x] & 1))
    rows.append((face, shade))
out = ["/* Generated by introlab/tools/gen_arcade_font.py from the arcade rom set. Do not edit. */",
       "#define FONTA_N 64", "static const uint8_t fonta[FONTA_N][2][8] = {"]
out += ["\t{{%s},{%s}}," % (",".join("0x%02X" % b for b in f), ",".join("0x%02X" % b for b in s)) for f, s in rows]
out += ["};", ""]
open(sys.argv[2], "w").write("\n".join(out))
