/* Byte copy is valid for every destination alignment and does not rely on
 * type-punning uint32_t accesses or stronger alias/alignment assumptions. */
static inline void r60_zoom_keep_copy(unsigned hz, uint8_t dst[16])
{
    const uint8_t *src = r60_zoom_keep_nibbles[hz];
    unsigned i;
    for (i = 0; i < 16; i++) dst[i] = src[i];
}
