#!/usr/bin/env python3
"""Emit sh_src/game_cfg.h: the per-game constants the engine C reads, from the game table.

    python3 tools/emit_game_cfg.py altbeast > sh_src/game_cfg.h

THE ONE SOURCE. A title's facts live in games/<name>/game.py TABLES, declared key by key in
kit/schema.py. This turns the int-valued port32x WRAM_* keys into `#define GAME_<KEY>`, so the
renderer, the 68K helper and the port runtime name a game cell instead of spelling AB's
address (2026-10-29, framework step 2). A key the title does not define is not emitted: code
that needs it then fails to compile for that title, which is the derivation gap made loud.
"""
import importlib.util
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from kit.schema import KEYS  # noqa: E402


def main():
    game = sys.argv[1] if len(sys.argv) > 1 else 'altbeast'
    path = os.path.join(ROOT, 'games', game, 'game.py')
    spec = importlib.util.spec_from_file_location('game_' + game, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    tables = mod.TABLES
    out = ['/* GENERATED by tools/emit_game_cfg.py %s from games/%s/game.py -- do not edit. */' % (game, game),
           '#ifndef GAME_CFG_H', '#define GAME_CFG_H']
    regions = tables.get('REGIONS')
    if regions:
        # one row per region: the menu's labels and the DIPs that board boots with
        out.append('#define GAME_REGIONS_N %du   /* regional sets one rom boots */' % len(regions))
        out.append('#define GAME_REGIONS_NAMES {%s}' % ', '.join('"%s"' % r[0] for r in regions))
        out.append('#define GAME_REGIONS_DSW1 {%s}' % ', '.join('0x%02Xu' % r[2] for r in regions))
        out.append('#define GAME_REGIONS_DSW2 {%s}' % ', '.join('0x%02Xu' % r[3] for r in regions))
    dips = tables.get('DIPS')
    if dips:
        # the DIP sheet, flattened: per switch its name, bank, mask and slice of the option list
        first, n = [], 0
        for d in dips:
            first.append(n); n += len(d[3])
        out.append('#define GAME_DIPS_N %du   /* switches on the arcade DIP sheet */' % len(dips))
        out.append('#define GAME_DIP_NAMES {%s}' % ', '.join('"%s"' % d[0] for d in dips))
        out.append('#define GAME_DIP_BANK {%s}' % ', '.join('%du' % d[1] for d in dips))
        out.append('#define GAME_DIP_MASK {%s}' % ', '.join('0x%02Xu' % d[2] for d in dips))
        out.append('#define GAME_DIP_FIRST {%s}' % ', '.join('%du' % f for f in first))
        out.append('#define GAME_DIP_COUNT {%s}' % ', '.join('%du' % len(d[3]) for d in dips))
        out.append('#define GAME_DIP_LABELS {%s}' % ', '.join('"%s"' % l for d in dips for l, _ in d[3]))
        out.append('#define GAME_DIP_VALUES {%s}' % ', '.join('0x%02Xu' % v for d in dips for _, v in d[3]))
    for k in KEYS:
        if k.layer != 'port32x' or not (k.name.startswith(('WRAM_', 'MENU_', 'DSW2_'))
                                        or k.name in ('TITLE', 'ROUNDS')):
            continue
        v = tables.get(k.name)
        if v is None:
            continue
        if isinstance(v, str):
            out.append('#define GAME_%-18s "%s"   /* %s */' % (k.name, v, k.what[:70]))
        elif isinstance(v, int) and not isinstance(v, bool):
            fmt = '0x%06Xu' if k.name.startswith('WRAM_') else ('0x%02Xu' if k.name.startswith('DSW2_') else '%du')
            out.append(('#define GAME_%-18s ' + fmt + '   /* %s */') % (k.name, v, k.what[:70]))
        elif isinstance(v, list) and v and isinstance(v[0], tuple):
            # a menu choice list: its count, its labels and its DIP bits, as C initialisers
            out.append('#define GAME_%s_N %du   /* %s */' % (k.name, len(v), k.what[:70]))
            out.append('#define GAME_%s_NAMES {%s}' % (k.name, ', '.join('"%s"' % n for n, _ in v)))
            out.append('#define GAME_%s_BITS {%s}' % (k.name, ', '.join('0x%02Xu' % b for _, b in v)))
    out.append('#endif')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
