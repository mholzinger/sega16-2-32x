# -*- coding: utf-8 -*-
# Generate the per-function COVERAGE TABLE, in the format that drove the prior
# Kyocera decompile from 12 to 83 PORTED of 93 functions
# (~/src/kyocera-2235/analysis/coverage.md).
#   tools/ghidra_run.sh script f1_coverage_table.py OUT.md [executed_pcs.json]
#
# Columns: entry, bytes, instructions, callers, name, class, EXECUTED (proven by
# an oracle trace), DECOMPILED, and STATUS. Status starts at ANALYZED for
# everything Ghidra decompiled and UNTOUCHED for what it did not; PORTED is set
# by hand as F2 lands each routine, so "the entire game is decoded" becomes
# checkable instead of claimed.
import json, os, re
from ghidra.app.decompiler import DecompInterface
from ghidra.util.task import ConsoleTaskMonitor

args = getScriptArgs()
OUT = args[0] if args else '/tmp/coverage.md'
PCS = set()
if len(args) > 1 and os.path.exists(args[1]):
    PCS = set(int(s, 16) for s in json.load(open(args[1])))

ROOT = '/Users/mikeholzinger/src/sega16-2-32x'
CLASSES = {}
row = re.compile(r'\|\s*0x([0-9A-Fa-f]+)\s*\|\s*(\d+)\s*\|\s*(\d+)\s*\|\s*([^|]*?)\s*\|')
fmap = os.path.join(ROOT, 'docs/audit/function_map.md')
if os.path.exists(fmap):
    for l in open(fmap):
        m = row.match(l)
        if m:
            CLASSES[int(m.group(1), 16)] = m.group(4).strip()

listing = currentProgram.getListing()
fm = currentProgram.getFunctionManager()
di = DecompInterface(); di.openProgram(currentProgram)
mon = ConsoleTaskMonitor()
BEH = ['animation','draws','palette','sound','motion','collision','state change',
       'claim/lock','despawns']
rows = []
for f in fm.getFunctions(True):
    a = f.getEntryPoint().getOffset()
    nb = f.getBody().getNumAddresses()
    ni = 0; ex = 0
    it = listing.getInstructions(f.getBody(), True)
    while it.hasNext():
        i = it.next(); ni += 1
        if i.getAddress().getOffset() in PCS: ex += 1
    cl = CLASSES.get(a, '-')
    ntag = sum(1 for t in BEH if t in cl)
    res = di.decompileFunction(f, 30, mon)
    dec = bool(res and res.decompileCompleted())
    rows.append((a, nb, ni, len(f.getCallingFunctions(mon)), f.getName(), cl,
                 ntag, ex, dec))
rows.sort()
core = [r for r in rows if r[6] >= 5]
with open(OUT, 'w') as fh:
    fh.write('# Altered Beast: port coverage\n\n')
    fh.write('Generated by `tools/ghidra/f1_coverage_table.py`. Format follows\n'
             '`~/src/kyocera-2235/analysis/coverage.md`, which drove that project\n'
             'from 12 to 83 PORTED of 93 functions.\n\n')
    fh.write('- **EXEC** = instructions an oracle trace was observed executing.\n'
             '- **CORE** = carries 5+ behaviour tags: an object handler, the part\n'
             '  needing a reading rather than a mechanical translation.\n'
             '- **STATUS**: UNTOUCHED -> ANALYZED (decompiled) -> PORTED (by hand,\n'
             '  as F2 lands it and its L1 differential passes).\n\n')
    fh.write('| functions | bytes | instrs | decompiled | core (5+ tags) | any EXEC |\n')
    fh.write('|---|---|---|---|---|---|\n')
    fh.write('| %d | %d | %d | %d | %d | %d |\n\n'
             % (len(rows), sum(r[1] for r in rows), sum(r[2] for r in rows),
                sum(1 for r in rows if r[8]), len(core),
                sum(1 for r in rows if r[7])))
    fh.write('| entry | bytes | instrs | callers | name | class | CORE | EXEC | STATUS |\n')
    fh.write('|---|---|---|---|---|---|---|---|---|\n')
    for a, nb, ni, nc, nm, cl, nt, ex, dec in rows:
        fh.write('| 0x%05X | %d | %d | %d | %s | %s | %s | %d/%d | %s |\n'
                 % (a, nb, ni, nc, nm, cl[:48], 'CORE' if nt >= 5 else '',
                    ex, ni, 'ANALYZED' if dec else 'UNTOUCHED'))
print('wrote %s: %d functions, %d decompiled, %d core, %d with executed code'
      % (OUT, len(rows), sum(1 for r in rows if r[8]), len(core),
         sum(1 for r in rows if r[7])))
