#!/usr/bin/env python3
"""THE MASTER'S HOT SET, CHOSEN FROM A PROFILE, NOT BY HAND (PORTHOT2, 2026-10-24).

The port runs the translated game from CART (.portcode) and the cart .text. The MiSTer
core holds DTACK for a full SDRAM access on every cart read (srcref/S32X_MiSTer
rtl/32X/IF.sv RS_MD_WAIT/RS_MD_READ), so a cart-resident function that misses the
SH-2's 4 KB cache pays a wait per line fill that ares does not charge. This picks the
functions whose WAIT per byte is highest and writes them, with the region each goes to,
to tools/hot_set.txt, which the build reads (Makefile PORTHOT2=1).

    wait = mean_cyc * (1 - 1.04 / cpi)      ares-profile cycles above the instruction floor

Input: the merged ares --profile table (columns name, region, bytes, mean_cyc_vint, cpi),
made by scratchpad hot/profile/merge.py over four windows (demo 1, demo 2, the neff fight,
the boss smoke). Excluded: what is already in SDRAM, cache-resident code (cpi < MIN_CPI),
main_entry (6 KB at a flat 3k), and names no mechanism can move (MOVABLE below).

    python3 tools/hot_set.py --profile hot_merged.csv --budget 4700 [--region 2]
    python3 tools/hot_set.py --profile ... --budget 12000 --budget3 0   (region 2 only)
"""
import argparse, csv, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MIN_CPI = 2.0
NEVER = {'main_entry'}
# Runtime functions outside the generated unit carry the attribute in their source
# (PORTHOT2 in sh_src/port_l2.c); a name not listed here and not generated is not movable.
RUNTIME = {'port_object_dispatch', 'port_zoom_scale', 'port_walk_player_slots',
           'port_despawn_index', 'port_call68_at'}


def generated_names():
    """function names defined in the generated unit's input + hand files"""
    names = set()
    src = os.path.join(ROOT, 'build', 'port', 'sh_src', 'portfull', 'altbeast_port.c')
    if not os.path.exists(src):            # the unit is cport_prep OUTPUT; the build copy is current
        src = os.path.join(ROOT, 'sh_src', 'portfull', 'altbeast_port.c')
    if os.path.exists(src):
        for m in re.finditer(r'^(?:\w+[\w \*]*?)\b(\w+)\s*\([^;]*$', open(src).read(), re.M):
            names.add(m.group(1))
    hand = os.path.join(ROOT, 'sh_src', 'portfull', 'hand')
    if os.path.isdir(hand):
        names |= {f[:-2] for f in os.listdir(hand) if f.endswith('.c')}
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--profile', required=True)
    ap.add_argument('--budget', type=int, required=True, help='bytes for region 2 (.ramtext2)')
    ap.add_argument('--budget3', type=int, default=0, help='bytes for region 3 (.ramtext3)')
    ap.add_argument('--out', default=os.path.join(ROOT, 'tools', 'hot_set.txt'))
    a = ap.parse_args()
    gen = generated_names()
    rows = []
    for r in csv.DictReader(open(a.profile)):
        n = r['name'].lstrip('_')
        if r['region'] == 'sdram' or n in NEVER:
            continue
        cpi = float(r['cpi']); b = int(r['bytes']); m = float(r['mean_cyc_vint'])
        if cpi < MIN_CPI or b <= 0:
            continue
        kind = ('thunk' if n.startswith(('thk_', 'thk0_')) else
                'runtime' if n in RUNTIME else
                'generated' if n in gen else None)
        if kind is None:
            continue
        w = m * (1.0 - 1.04 / cpi)
        rows.append((w / b, w, b, n, kind))
    rows.sort(reverse=True)
    pick, used, used3, tw = [], 0, 0, 0.0
    for wpb, w, b, n, kind in rows:
        b4 = (b + 3) & ~3
        if used + b4 <= a.budget:
            pick.append((n, 2, b, w, kind)); used += b4; tw += w
        elif used3 + b4 <= a.budget3:
            pick.append((n, 3, b, w, kind)); used3 += b4; tw += w
    with open(a.out, 'w') as fh:
        fh.write('# GENERATED by tools/hot_set.py -- do not edit by hand. name@region  bytes  wait/vint  kind\n')
        fh.write('# profile %s, region 2 budget %d (used %d), region 3 budget %d (used %d), wait %.0f cyc/vint\n'
                 % (os.path.basename(a.profile), a.budget, used, a.budget3, used3, tw))
        for n, reg, b, w, kind in pick:
            fh.write('%s@%d %d %.0f %s\n' % (n, reg, b, w, kind))
    print('hot_set: %d functions, region 2 %d B, region 3 %d B, wait %.0f cyc/vint -> %s'
          % (len(pick), used, used3, tw, a.out))


if __name__ == '__main__':
    sys.exit(main())
