#!/usr/bin/env python3
"""The register file the arcade's dispatcher had, per object slot, from the oracle.

    python3 tools/cport_dispregs.py sh_src/portfull

WHY. The port's hand-written dispatcher called every handler with NO arguments, and
that is a correctness bug rather than an approximation: `sprite_build_depth_banded`
gates its hide-or-draw decision on `p_D6`, so with D6 reading 0 nothing is ever
hidden -- every object gets its sprite record filled and bit 3 of its flag byte set,
every frame (FULL-PORT.md 26).

The 68K's `object_dispatcher` sets NONE of these itself -- it only walks the slots
and calls -- so D3/D6/D7 are inherited from ITS caller and threaded through the
handler chain in registers. That cannot be derived from the dispatcher alone, so
this table is the ORACLE's answer: the 232 vectors captured at the dispatcher's own
call site (caller 0x0039AC) carry the full register file per call.

THIS IS A DIAGNOSTIC, NOT A PORT. A shipping port cannot read an arcade capture. It
exists to prove the mechanism and bound the payoff before anyone spends a Ghidra
cycle on deriving the chain.

HONEST LIMITS, both worth knowing before reading any number off it:
  * One vector per slot. A slot appears in several vectors across the captured
    window with DIFFERENT register values (D6 is a running sprite-record cursor,
    not a per-slot constant), so this picks the first and the choice is arbitrary.
  * A-registers are 68K addresses and are translated at run time through WRAM_BASE
    or ROM_BASE; a value in neither range is passed through unchanged.
"""
import json, os, sys

outdir = sys.argv[1] if len(sys.argv) > 1 else 'sh_src/portfull'
# L1_VEC lets a FRAME-MATCHED capture replace the general corpus. That matters: D6
# is a running sprite-record cursor, so a vector from another frame carries the wrong
# D6 and supplying it is worse than supplying zero (measured 2026-10-01: net -2 and
# three object cells made worse). Capture with L1_WINDOWS=<frame> and extract to a
# separate file, then point this at it.
VEC = os.environ.get('L1_VEC', 'docs/proof/l1_vectors.jsonl')
CALLER = '0039AC'

first = {}
count = {}
for line in open(VEC):
    line = line.strip()
    if not line:
        continue
    v = json.loads(line)
    if v.get('caller') != CALLER:
        continue
    a = v['entry']['a']
    A6 = a[6] & 0xFFFFFFFF
    slot = ((A6 & 0xFFFFFF) - 0xFFC000) // 0x80
    if not (0 <= slot < 64):
        continue
    count[slot] = count.get(slot, 0) + 1
    if slot not in first:
        first[slot] = v['entry']

RN = ['D0','D1','D2','D3','D4','D5','D6','D7','A0','A1','A2','A3','A4','A5','A6']
out = ['/* GENERATED by tools/cport_dispregs.py -- the ARCADE\'s register file at the',
       ' * object dispatcher\'s call site, per slot. A DIAGNOSTIC: see that file. */',
       '#include "ghidra_types.h"',
       'extern char WRAM_BASE[], ROM_BASE[];',
       '',
       '/* r[0..7] = D0..D7, r[8..14] = A0..A6 -- the order the generated thunks index */',
       'const unsigned char port_dispregs_have[64] = {']
have = ''.join('1,' if s in first else '0,' for s in range(64))
out.append('    ' + have)
out += ['};',
        'const unsigned int port_dispregs[64][15] = {']
for s in range(64):
    if s not in first:
        out.append('    { 0 },')
        continue
    e = first[s]
    vals = [e['d'][i] & 0xFFFFFFFF for i in range(8)] + [e['a'][i] & 0xFFFFFFFF for i in range(7)]
    out.append('    { ' + ', '.join('0x%08Xu' % v for v in vals) + ' },   /* slot %d, %d vector(s) seen */' % (s, count[s]))
out += ['};', '']
out += ['/* A-REGISTERS ARE 68K ADDRESSES. Translate at use, the same region split W68',
        ' * uses; a value in neither range passes through unchanged. */',
        'unsigned int port_dispreg_fix(unsigned int i, unsigned int v)',
        '{',
        '    if (i < 8u) return v;                       /* a D register is data */',
        '    if ((v & 0xFFFFFFu) >= 0xFFC000u)',
        '        return (unsigned int)(WRAM_BASE + ((v & 0xFFFFFFu) - 0xFFC000u));',
        '    if ((v & 0xFFFFFFu) < 0x40000u && v)',
        '        return (unsigned int)(ROM_BASE + (v & 0x3FFFFu));',
        '    return v;',
        '}', '']
open(os.path.join(outdir, 'dispregs.c'), 'w').write('\n'.join(out))
print('dispregs: %d of 64 slots have an oracle register file (%d vectors at caller %s)'
      % (len(first), sum(count.values()), CALLER))
