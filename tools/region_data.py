#!/usr/bin/env python3
"""Take the program bytes a regional set has and the reference lacks, at build time.

    python3 tools/region_data.py altbeast sh_src

Reads games/<title>/game.py REGIONS (label, MAME set, DSW1, DSW2) and REGION_DATA
(region, lo, hi), builds each needed set's prog68k.bin with tools/romset.py, and writes
<out>/region_data.s: one .rodata symbol per range, `region<N>_<lo as 6 hex digits>`, with
the bytes inline. The bytes are the arcade program's, so they are generated into the build
from the owner's MAME zip and never committed, the same as every other rom-derived blob.

A title with no REGION_DATA still gets a valid, empty region_data.s. A REGION_DATA row whose
set cannot be built is an ERROR: a one-rom build that silently lacked a region's data would
draw the reference set's picture under the other region's name.
"""
import importlib.util
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    game, out = sys.argv[1], sys.argv[2]
    spec = importlib.util.spec_from_file_location('game_' + game,
                                                  os.path.join(ROOT, 'games', game, 'game.py'))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    regions = mod.TABLES.get('REGIONS') or []
    rows = mod.TABLES.get('REGION_DATA') or []
    lines = ['! GENERATED by tools/region_data.py %s from games/%s/game.py -- do not edit.' % (game, game),
             '        .section .rodata']
    for region, lo, hi in rows:
        if region >= len(regions):
            raise SystemExit('region_data: REGION_DATA names region %d; REGIONS has %d rows'
                             % (region, len(regions)))
        rset = regions[region][1]
        prog = os.path.join(ROOT, 'roms', rset, 'prog68k.bin')
        if not os.path.exists(prog):
            r = subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'romset.py'), rset],
                               cwd=ROOT)
            if r.returncode or not os.path.exists(prog):
                raise SystemExit('region_data: region %d (%s) needs roms/%s/prog68k.bin and '
                                 'tools/romset.py could not build it: add mame/%s.zip (or a '
                                 'merged parent zip)' % (region, regions[region][0], rset, rset))
        data = open(prog, 'rb').read()[lo:hi]
        sym = 'region%d_%06x' % (region, lo)
        # 16-aligned: the readers copy with 32-bit loads (FUN_00002622 moves palette rows
        # as longs), and an SH-2 long load from a 2-mod-4 address faults
        lines += ['        .balign 16', '        .global _%s' % sym, '_%s:' % sym]
        for i in range(0, len(data), 16):
            lines.append('        .byte   ' + ','.join('0x%02x' % b for b in data[i:i + 16]))
    open(os.path.join(out, 'region_data.s'), 'w').write('\n'.join(lines) + '\n')
    print('region_data: %d range(s), %d bytes -> %s/region_data.s'
          % (len(rows), sum(hi - lo for _, lo, hi in rows), out))


if __name__ == '__main__':
    main()
