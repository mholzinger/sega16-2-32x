#!/usr/bin/env python3
"""The 68K program, disassembled FROM REAL FUNCTION BOUNDARIES, as one greppable file.

    python3 tools/disasm_funcs.py                 # -> build/prog68k_funcs.asm
    python3 tools/disasm_funcs.py --fn FUN_0000d776
    grep -n 'movel %fp,%sp@-' build/prog68k_funcs.asm        # every A6 push, with its function

Every line is `<addr>: <bytes> <mnemonic>` under a `== <name> <start>` header, so a grep
answers "which function does this instruction live in" -- which is how the port's idioms
get found (the A6 switches around the palette helpers, the `bsr ; bcc ; jmp (a0)` sites,
the computed jumps). A LINEAR sweep of the ROM cannot do this: it decodes the embedded
tables as instructions and invents operands, so every count it produces is part noise.
The ranges come from docs/audit/func_ranges.txt (Ghidra's own boundaries, 938 of them),
so each range starts at a real instruction and nothing outside a function body is decoded.

It writes under build/ because it is generated: the loop greps the file, and the file is
rebuilt from the ROM and the range list in about 40 seconds.
"""
import os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OD = os.environ.get('M68K_OBJDUMP',
                    os.path.expanduser('~/src/marsdev/mars/m68k-elf/bin/m68k-elf-objdump'))
ROM = os.path.join(ROOT, 'roms', 'altbeast', 'prog68k.bin')
RANGES = os.path.join(ROOT, 'docs', 'audit', 'func_ranges.txt')
OUT = os.environ.get('DISASM_OUT', os.path.join(ROOT, 'build', 'prog68k_funcs.asm'))


def ranges():
    for line in open(RANGES):
        if line.startswith('#'):
            continue
        f = line.split()
        if len(f) == 4:
            yield f[3], int(f[0], 16), int(f[1], 16)


def disasm(lo, hi):
    r = subprocess.run([OD, '-b', 'binary', '-m', '68000', '--adjust-vma=0',
                        '--start-address', '0x%x' % lo, '--stop-address', '0x%x' % (hi + 1),
                        '-D', ROM], capture_output=True, text=True)
    return [re.sub(r'\s+', ' ', x).strip() for x in r.stdout.splitlines()
            if re.match(r'^\s+[0-9a-f]+:', x)]


def main():
    only = None
    if '--fn' in sys.argv:
        only = sys.argv[sys.argv.index('--fn') + 1]
    if not os.path.exists(OD):
        sys.exit('disasm_funcs: no 68K objdump at %s (set M68K_OBJDUMP)' % OD)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    n = 0
    with open(OUT, 'w') as out:
        out.write('# GENERATED by tools/disasm_funcs.py from roms/altbeast/prog68k.bin\n'
                  '# + docs/audit/func_ranges.txt. One function per `== name start` block.\n')
        for name, lo, hi in ranges():
            if only and name != only:
                continue
            out.write('== %s 0x%05X\n' % (name, lo))
            for l in disasm(lo, hi):
                out.write(l + '\n')
            n += 1
    print('disasm_funcs: %d functions -> %s' % (n, OUT))


if __name__ == '__main__':
    main()
