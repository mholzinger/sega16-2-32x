#!/usr/bin/env python3
"""Generate the L2 register seed: prove (or refute) the 977-reads-zero-writes gap.

    python3 tools/cport_l2seed.py sh_src/portfull

FULL-PORT.md 14 says the port reads 977 inherited 68K registers and writes none,
so every read returns zero, and that this is why the object handlers write wrong
values. That is a hypothesis until the registers are supplied and the L2 score
moves.

This supplies them for the four handlers the captured frame dispatches, from the
arcade's own register file at the moment of each call (tools/l1_oracle.lua at
window 9000, caller 0x0039AC), mapped to pseudo-registers by
docs/audit/reg_convention.json.

IT IS AN EXPERIMENT, NOT A PORT. The values are one frame's, read from an oracle;
nothing here generalises to a second frame, let alone to play. It exists to answer
one question with a number: if the registers are right, how many of the 208 wrong
bytes go away?
"""
import json, os, re, sys

outdir = sys.argv[1] if len(sys.argv) > 1 else 'sh_src/portfull'
conv = {r['name']: (r.get('storage') or {}) for r in
        json.load(open('docs/audit/reg_convention.json'))}
# THE CAPTURE IS A /tmp FILE AND NOTHING IN THIS REPO PRODUCES IT.
#
# It was written ad hoc from tools/l1_oracle.lua on 2026-09-28 (commit 16e1b250) and
# never committed -- it is ROM-derived, so it could not be. A /tmp build input is an
# unreproducible build: when /tmp was cleared, `make ... PORTFULL=1` died here with
# a FileNotFoundError and no rom (2026-10-02).
#
# DEGRADE, DO NOT INVENT. With no capture this emits an EMPTY port_l2_seed, which is
# the honest state -- PORTREGS is a diagnostic flag and the chain it proved
# (extraout/unaff write-back, FULL-PORT.md 14) is now built into cport_prep.py
# properly, so the experiment is superseded rather than needed.
_CAP = '/tmp/disp_regs.json'
if os.path.exists(_CAP):
    regs = json.load(open(_CAP))
else:
    regs = []
    print('l2seed: NO CAPTURE at %s -- emitting an EMPTY seed. PORTREGS is a no-op '
          'in this build.' % _CAP)

# the same region split cport_layout.py uses; an A-register holds a 68K ADDRESS
# and has to become an SH-2 pointer, a D-register is a plain value
def ptr(v):
    v &= 0xFFFFFFFF
    a = v & 0xFFFFFF
    if 0xFFC000 <= a <= 0xFFFFFF:
        return '((byte *)WRAM_BASE + 0x%Xu)' % (a - 0xFFC000)
    if a < 0x40000:
        return '((byte *)ROM_BASE + 0x%Xu)' % a
    return '((byte *)MMIO_BASE)'          # compacted; no faithful offset exists

WIDTH = {'b': 0xFF, 'w': 0xFFFF, '': 0xFFFFFFFF}

# KEYED ON THE SLOT, NOT THE HANDLER ADDRESS. The same handler runs on more than
# one object (0x0EE80 is on slots 16 and 17 in this very frame), and its A6 differs
# per slot -- a switch on the handler address produces duplicate cases and silently
# keeps only the first.
out = ['/* GENERATED by tools/cport_l2seed.py -- EXPERIMENT, see that file. */',
       '#include "ghidra_types.h"',
       '#include "pseudoregs.h"',
       'extern char WRAM_BASE[], ROM_BASE[], MMIO_BASE[];',
       '',
       'void port_l2_seed(unsigned int slot)',
       '{',
       '    switch (slot) {']
n_asgn = 0
for r in regs:
    a68 = int(r['callee'], 16)
    fn = 'FUN_0000%04x' % a68 if a68 <= 0xFFFF else 'FUN_000%05x' % a68
    fn = [k for k in conv if k.lower().endswith('%05x' % a68)] or [fn]
    st = conv.get(fn[0], {})
    slot = ((r['a'][6] & 0xFFFFFF) - 0xFFC000) // 0x80
    out.append('    case %du:   /* slot %d -> %s at 0x%05X */'
               % (slot, slot, fn[0], a68))
    for ps, storage in sorted(st.items()):
        m = re.match(r'([AD])(\d)([bw]?):(\d)', storage)
        if not m:
            continue
        cls, num, wid, _sz = m.groups()
        val = (r['a'] if cls == 'A' else r['d'])[int(num)]
        if cls == 'A' and not wid:
            out.append('        _r_%s = %s;' % (ps, ptr(val)))
        else:
            out.append('        _r_%s = 0x%Xu;' % (ps, val & WIDTH[wid]))
        n_asgn += 1
    out.append('        break;')
out += ['    default: break;',
        '    }',
        '}',
        '']
open(os.path.join(outdir, 'l2seed.c'), 'w').write('\n'.join(out))
print('l2seed: %d handlers, %d register assignments -> %s/l2seed.c'
      % (len(regs), n_asgn, outdir))
