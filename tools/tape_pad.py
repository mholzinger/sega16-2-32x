#!/usr/bin/env python3
"""The input tape as a table the port reads by game frame (measurement builds, PORTTAPEPAD).

    python3 tools/tape_pad.py <tape.csv> <arcade corpus dir> <out.h>

ares injects input once per WALL frame; when the port runs two game ticks in one frame both
see the same pad, so a tape replayed through ares lands 0 or 1 game frames late depending on
the frame's phase (2026-10-25: 17 of the first 40 edges on the arcade's tick, 23 one late).
The port instead applies this table at the start of each tick, indexed by its own
port_gf_count, which is exact.

Keys are the arcade's blink-step counts S(f-1) (tools/parity_play.py keyed_tape); the
attract/coin transitions move the two machines' counts apart and play holds them fixed, so
every entry from the calibration frame on waits for the offset the port measures itself:
its count at the first in-play tick TP_CAL_TICK minus the arcade's TP_CAL_S there.

Each entry is the PAD STATE after its events, in the arcade's form: the P1 byte active low
(md_src/md_main.c md_to_arcade: up 0x20 down 0x10 left 0x80 right 0x40, A punch 0x02,
B kick 0x04, C jump 0x01) and the service byte active high (coin 0x01 from x/y/z/mode,
start1 0x10; md_src/r60_shim.h R60_LIVEPAD), so the port writes it where l2m_io_live does.
"""
import csv, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from parity_play import gf_steps  # noqa: E402

P1_BIT = {'up': 0x20, 'down': 0x10, 'left': 0x80, 'right': 0x40, 'a': 0x02, 'b': 0x04, 'c': 0x01}
COIN = ('x', 'y', 'z', 'mode')


def main(tape, arcade, out):
    A = list(csv.DictReader(open(os.path.join(arcade, 'timeline.csv'))))
    af = [int(r['frame']) for r in A]
    S = dict(zip(af, gf_steps([int(r['gameframe']) for r in A])))
    ev = []
    for l in open(tape):
        if not l.strip() or l.startswith('#'):
            continue
        f = l.strip().split(',')
        if len(f) > 3 and f[3] not in ('', '1'):
            continue                                  # P1 only
        ev.append((int(f[0]), f[1], int(f[2])))
    ev.sort(key=lambda e: e[0])
    start = min((e[0] for e in ev if e[1] == 'start'), default=0)
    first_play = min((e[0] for e in ev if e[0] > start + 60), default=None)
    cal = None
    if first_play is not None:
        for r in A:
            f = int(r['frame'])
            if start + 60 < f < first_play and int(r['tick'], 16) >= 0x20:
                cal = (f, int(r['tick'], 16))
    if cal is None:
        raise SystemExit('tape_pad: no in-play arcade tick before the first play input')
    last, keyed = {}, []
    for i, (fr, btn, val) in enumerate(ev):
        # S(fr), not S(fr - 1): the arcade latches a pad change in the vblank IRQ4 that ENDS
        # frame fr, so its game first sees it in the pass after; the port applies the table at
        # tick start and its own irq4_handler latches it in that tick. Keyed on S(fr - 1) the
        # latched pad led the arcade by exactly one tick at every edge (2026-10-25).
        k = S.get(fr, 0)
        if btn in last and k <= last[btn]:
            k = last[btn] + 1                         # a press outlives the keying
        last[btn] = k
        keyed.append((k, i, fr, btn, val))
    keyed.sort()                                      # a bumped key may pass another button's
    held, rows = set(), []
    for k, _i, fr, btn, val in keyed:
        (held.add if val else held.discard)(btn)
        a = 0
        for b in held:
            a |= P1_BIT.get(b, 0)
        svc = 0x01 if any(b in held for b in COIN) else 0
        if 'start' in held:
            svc |= 0x01 if 'a' in held else 0x10
        st = (k, (~a) & 0xFF, svc, fr >= cal[0])
        if rows and rows[-1][0] == k and rows[-1][3] == st[3]:
            rows[-1] = st                             # same key: the later state wins
        else:
            rows.append(st)
    cal_from = next(i for i, r in enumerate(rows) if r[3])
    keys = [r[0] for r in rows]
    assert keys == sorted(keys), 'tape_pad: keys out of order'
    with open(out, 'w') as fh:
        fh.write('/* GENERATED by tools/tape_pad.py from %s and %s/timeline.csv: %d pad states,\n'
                 ' * calibration at arcade frame %d (tick 0x%X, count %d). Measurement builds only. */\n'
                 % (os.path.basename(tape), os.path.basename(arcade.rstrip('/')), len(rows), cal[0], cal[1], S[cal[0]]))
        fh.write('#define TP_N %d\n#define TP_CAL_TICK 0x%X\n#define TP_CAL_S %du\n#define TP_CAL_FROM %d\n'
                 % (len(rows), cal[1], S[cal[0]], cal_from))
        for name, ty, col in (('tp_key', 'unsigned short', 0), ('tp_p1', 'unsigned char', 1), ('tp_svc', 'unsigned char', 2)):
            fh.write('static const %s %s[TP_N] __attribute__((section(".tapepad"), used)) = {\n' % (ty, name))
            vals = [str(r[col]) for r in rows]
            for i in range(0, len(vals), 16):
                fh.write('    ' + ', '.join(vals[i:i + 16]) + ',\n')
            fh.write('};\n')
    print('tape_pad: %d states, calibration frame %d tick 0x%X, post-calibration from entry %d -> %s'
          % (len(rows), cal[0], cal[1], cal_from, out))


if __name__ == '__main__':
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    main(*sys.argv[1:])
