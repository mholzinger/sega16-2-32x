#!/usr/bin/env python3
"""sound_blob.py -- pack the sound lab's generated tables into one cart blob + a 68K table.

    python3 tools/sound_blob.py sndtest/md/render_music.h sndtest/md/sndmap_data.h build/sound/sound.bin md_src/sound_tab.h

The lab (sndtest/) keeps every stream as a C array inside two generated headers; the game
cannot afford them in the 68K's 512 KB ROM window, so they go into a cart section the 68K
reads through the banked 0x900000 window (bank 2 = cart 0x200000..0x2FFFFF). The 68K table
carries cart offsets, not pointers. Everything here is derived from the lab's headers, which
are themselves generated (tools/soundmap_build.py, tools/render_music.py) from the arcade's
Z80 driver and the VGZ rips; nothing is copied from any game.
"""
import re, sys, struct

def arrays(src):
    out = {}
    for m in re.finditer(r'static const uint8_t (\w+)\[(\d+)\] = \{(.*?)\};', src, re.S):
        name, n, body = m.group(1), int(m.group(2)), m.group(3)
        data = bytes(int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f]{2})', body))
        assert len(data) == n, (name, n, len(data))
        out[name] = data
    return out

def main():
    rm_path, sm_path, blob_path, tab_path = sys.argv[1:5]
    rm = open(rm_path).read(); sm = open(sm_path).read()
    ra = arrays(rm); sa = arrays(sm)
    blob = bytearray(); off = {}
    def put(name, data):
        while len(blob) & 1: blob.append(0xFF)
        off[name] = len(blob); blob.extend(data)
    # rendered music: cmd -> intro/loop streams (LZSS, the lab's format)
    rend = re.findall(r'\{\s*0x([0-9A-Fa-f]{2}),\s*(\w+),\s*(\d+),\s*(\w+),\s*(\d+)\s*\}', rm)
    for cmd, intro, ilen, loop, llen in rend:
        put(intro, ra[intro])
        if loop != intro: put(loop, ra[loop])
    # command map: 256 x {type, idx, sp} and the per-command raw tracks
    trks = re.findall(r'\{\s*(\w+),\s*(\d+),\s*(\d+)\s*\}', re.search(r'snd_trks\[\d+\] = \{(.*?)\};', sm, re.S).group(1))
    for name, n, loop in trks: put(name, sa[name])
    ents = re.findall(r'\{\s*(\d+),\s*(\d+),\s*(0x[0-9A-Fa-f]+|\d+)\s*\}', re.search(r'sndmap\[256\] = \{(.*?)\};', sm, re.S).group(1))
    assert len(ents) == 256, len(ents)
    open(blob_path, 'wb').write(bytes(blob))
    with open(tab_path, 'w') as f:
        f.write('/* AUTO-GENERATED by tools/sound_blob.py -- cart offsets into the .sounddata blob. Do not edit. */\n#include <stdint.h>\n')
        f.write('#define SND_BLOB_BYTES %du\n' % len(blob))
        f.write('struct snd_rend { uint8_t cmd; uint32_t intro, intro_len, loop, loop_len; };\n')
        f.write('static const struct snd_rend snd_rend[%d] = {\n' % len(rend))
        for cmd, intro, ilen, loop, llen in rend:
            f.write('\t{ 0x%s, %du, %su, %du, %su },\n' % (cmd, off[intro], ilen, off[loop], llen))
        f.write('};\n#define SND_REND_COUNT %d\n' % len(rend))
        f.write('struct snd_trk { uint32_t off, len; uint8_t loop; };\n')
        f.write('static const struct snd_trk snd_trks[%d] = {\n' % len(trks))
        for name, n, loop in trks: f.write('\t{ %du, %su, %s },\n' % (off[name], n, loop))
        f.write('};\n')
        f.write('struct snd_ent { uint8_t type; uint8_t idx; uint8_t sp; };\n#define SND_NONE 0\n#define SND_MUSIC 1\n#define SND_YMSFX 2\n')
        f.write('static const struct snd_ent sndmap[256] = {\n')
        for t, i, sp in ents: f.write('\t{ %s, %s, %s },\n' % (t, i, sp))
        f.write('};\n')
    print('blob %d bytes (%d KB), %d rendered, %d tracks' % (len(blob), len(blob) // 1024, len(rend), len(trks)))

if __name__ == '__main__':
    main()
