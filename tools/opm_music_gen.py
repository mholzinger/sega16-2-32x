#!/usr/bin/env python3
"""The overflow channels' YM2151 register streams as a C table for the SH-2 synth lane. KIT.

The sound cart's Z80 player loops each song WHOLE (tools/build_vgm_music.py: the gag's
behaviour, a re-snapshot at every wrap). The lane does the same: per song command, every
YM2151 write that touches --channels, from the rip's start to its end, as (delta in lane
samples, reg << 8 | val) rows, and the song's length in samples for the wrap. The lane's
clock is the PWM sample clock (--rate: the mixer's rate as the hardware really runs it).

  tools/opm_music_gen.py --map "0x94=01 Rise....vgz" ... --audio DIR --rate 16000 \
      --channels 6,7 --out sndtest/sh/opm_music.h

Output is derived from the rips and never committed (.gitignore).
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import opm_ab                                # noqa: E402
from vgm2ym import load                      # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--map', nargs='+', required=True, help='cmd=vgz-basename entries')
    ap.add_argument('--audio', required=True)
    ap.add_argument('--channels', default='6,7')
    ap.add_argument('--rate', type=float, default=16002.3, help='the PWM sample clock as the hardware runs it (23011361 / 1438)')
    ap.add_argument('--row-scale', type=float, default=1.0,
                    help='row clock = rate * this: 1.000237 follows the Z80 player, whose millisecond is Timer B quantised (player.asm)')
    ap.add_argument('--attr', default='', help='an attribute put before every row array, e.g. a cart section for the game')
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    chans = [int(c) for c in a.channels.split(',')]
    songs = []
    total_rows = 0
    for m in a.map:
        cmd_s, fname = m.split('=', 1)
        cmd = int(cmd_s, 16)
        path = os.path.join(a.audio, fname)
        seg, loop_t, total_s = load(path)
        ev = opm_ab.ym_events(path, chans, total_s + 1.0)
        rows = []
        last = 0
        for t, r, v in ev:
            ts = int(t * a.rate * a.row_scale / opm_ab.FM_RATE)
            d = ts - last
            while d > 65535:
                rows.append((65535, 0xff, 0))
                d -= 65535
            rows.append((d, r, v))
            last = ts
        n = int(total_s * a.rate * a.row_scale)
        songs.append((cmd, rows, n, fname))
        total_rows += len(rows)
        print(f'  0x{cmd:02X} {fname[:34]:34} {total_s:6.1f}s {len(ev):5d} writes {len(rows):5d} rows',
              file=sys.stderr)
    with open(a.out, 'w') as f:
        f.write('/* AUTO-GENERATED by tools/opm_music_gen.py: the overflow channels %s of each song\n'
                ' * command as YM2151 writes on the lane clock (%.1f Hz). Do not edit. */\n'
                '#include <stdint.h>\n\n' % (a.channels, a.rate))
        f.write('#define OPM_MUSIC_RATE %d\n#define OPM_MUSIC_CHMASK 0x%02x\n'
                % (int(round(a.rate)), sum(1 << c for c in chans)))
        f.write('#define OPM_MUSIC_SPF_Q8 %d   /* lane samples per NTSC frame (59.9227 Hz), x256 */\n\n'
                % int(round(a.rate / 59.9227 * 256)))
        for cmd, rows, n, fname in songs:
            f.write('%sstatic const uint16_t opm_rows_%02X[%d][2] = {\n' % (a.attr + ' ' if a.attr else '', cmd, len(rows)))
            for i, (d, r, v) in enumerate(rows):
                f.write('{%d,0x%04x},' % (d, (r << 8) | v))
                if i % 8 == 7:
                    f.write('\n')
            f.write('};\n')
        f.write('\nstruct opm_song { uint8_t cmd; uint32_t rows; uint32_t samples; const uint16_t (*row)[2]; };\n')
        f.write('%sstatic const struct opm_song opm_music[%d] = {\n' % (a.attr + ' ' if a.attr else '', len(songs)))
        for cmd, rows, n, fname in songs:
            f.write('\t{ 0x%02X, %d, %d, opm_rows_%02X },\n' % (cmd, len(rows), n, cmd))
        f.write('};\n#define OPM_MUSIC_COUNT %d\n' % len(songs))
    print('opm_music.h: %d songs, %d rows (%d KB)' % (len(songs), total_rows, total_rows * 4 // 1024),
          file=sys.stderr)


if __name__ == '__main__':
    main()
