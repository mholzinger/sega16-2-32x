#!/usr/bin/env python3
"""The register stream of a song's overflow channels as a C table for the SH-2 bench. KIT.

The synthetic bench (two feedback-7 voices keyed for ever) is the engine's worst case;
in a song the two channels rest, decay and retrigger, and the engine's silence skip and
envelope schedule only pay off there. This writes the YM2151 writes that touch
--channels, from the rip, to --secs, as (delta in output samples at --rate, reg, val)
rows: sndtest/sh/opm_bench.c replays them through the engine and times it.

  tools/opm_song_bench_gen.py --vgz "<rip>" --channels 6,7 --secs 20 --rate 15625 \
      --out sndtest/sh/opm_bench_song.h

Output is derived from the rip and never committed (.gitignore).
"""
import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import opm_ab                                # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--vgz', required=True)
    ap.add_argument('--channels', default='6,7')
    ap.add_argument('--secs', type=float, default=20.0)
    ap.add_argument('--rate', type=int, default=15625)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    chans = [int(c) for c in a.channels.split(',')]
    ev = opm_ab.ym_events(a.vgz, chans, a.secs)
    rows = []
    last = 0
    for t, r, v in ev:
        ts = int(t * a.rate / opm_ab.FM_RATE)
        d = ts - last
        while d > 65535:                     # a long rest: no-op rows (reg 0xff) keep the delta in 16 bits
            rows.append((65535, 0xff, 0))
            d -= 65535
        rows.append((d, r, v))
        last = ts
    n = int(a.secs * a.rate)
    with open(a.out, 'w') as f:
        f.write('/* generated by tools/opm_song_bench_gen.py from %s: channels %s, %.1f s at %d Hz */\n'
                % (os.path.basename(a.vgz), a.channels, a.secs, a.rate))
        f.write('#define OPM_SONG_RATE %d\n#define OPM_SONG_SAMPLES %d\n#define OPM_SONG_CHMASK 0x%02x\n'
                % (a.rate, n, sum(1 << c for c in chans)))
        f.write('#define OPM_SONG_ROWS %d\nstatic const uint16_t opm_song_rows[OPM_SONG_ROWS][2] = {\n' % len(rows))
        for i, (d, r, v) in enumerate(rows):
            f.write('{%d,0x%04x},' % (d, (r << 8) | v))
            if i % 8 == 7:
                f.write('\n')
        f.write('};\n')
    print('%d writes -> %d rows, %d samples' % (len(ev), len(rows), n))


if __name__ == '__main__':
    main()
