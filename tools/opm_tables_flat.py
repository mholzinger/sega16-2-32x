#!/usr/bin/env python3
"""The engine's RAM tables as constants, for a build with no RAM to spare. KIT.

sndtest/opm/opm.c fills three tables at init (sin_ram: the quarter-wave log-sine unfolded
over the period; pow_flat: the power table flat over its whole index range; step_ram: the
phase-step table) from sndtest/opm/opm_tables.h (ymfm, BSD). Beside the game the SDRAM
is full, so OPM_TABLES_CONST builds read them from the cart instead: this writes them as
const arrays, byte for byte what opm_init would have filled.

  tools/opm_tables_flat.py [--out sndtest/opm/opm_tables_flat.h]
"""
import argparse
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def table(src, name):
    m = re.search(name + r'\[\d*\]\s*=\s*\{([^}]*)\}', src)
    return [int(x, 0) for x in re.findall(r'0x[0-9a-fA-F]+|\d+', m.group(1))]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'sndtest', 'opm', 'opm_tables_flat.h'))
    a = ap.parse_args()
    src = open(os.path.join(ROOT, 'sndtest', 'opm', 'opm_tables.h')).read()
    sin, pw, step = table(src, 'opm_sin'), table(src, 'opm_pow'), table(src, 'opm_step')
    assert len(sin) == 256 and len(pw) == 256 and len(step) == 768
    sin1024 = [sin[((~i if (i & 256) else i)) & 255] for i in range(1024)]
    # 13 x 256 (6.5 KB): the const build keeps op_out's range check instead of the 12.5 KB
    # zero-padded table (cart room beside the game is tight, 2026-10-31)
    pow_flat = [pw[i & 255] >> (i >> 8) for i in range(13 * 256)]
    with open(a.out, 'w') as f:
        f.write('/* generated by tools/opm_tables_flat.py from opm_tables.h: the engine\'s RAM tables as\n'
                ' * constants (OPM_TABLES_CONST), byte for byte what opm_init fills. OPM_TABLES_ATTR places\n'
                ' * them (a cart section beside the game). Do not edit. */\n'
                '#ifndef OPM_TABLES_ATTR\n#ifdef OPM_TABLES_IN_OPMROWS\n'
                '#define OPM_TABLES_ATTR __attribute__((section(".opmrows")))   /* the game: a plain define, quotes break the flag stamp */\n'
                '#else\n#define OPM_TABLES_ATTR\n#endif\n#endif\n')
        for name, typ, vals, per in (('opm_sin1024', 'uint16_t', sin1024, 16),
                                     ('opm_pow_flat', 'uint16_t', pow_flat, 16),
                                     ('opm_step_flat', 'uint32_t', step, 8)):
            f.write('OPM_TABLES_ATTR static const %s %s[%d] = {\n' % (typ, name, len(vals)))
            for i in range(0, len(vals), per):
                f.write('\t' + ','.join('0x%x' % v for v in vals[i:i + per]) + ',\n')
            f.write('};\n')
    print('%s: sin 1024, pow %d, step 768 (%d KB)' % (a.out, len(pow_flat), (2 * 1024 + 2 * len(pow_flat) + 4 * 768) // 1024))


if __name__ == '__main__':
    main()
