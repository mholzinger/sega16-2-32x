#!/usr/bin/env python3
"""Cut the sound lab's speech bank (sndtest/sh/speech_bank.c, tools/speech_bake.py output:
IMA ADPCM at 16 kHz, even sample = LOW nibble) into one binary blob for the cart plus a
table header, and derive the sound-command -> bank-entry map from the lab's tap manifest
(sndtest/speech/manifest.json). Per command byte the LONGEST utterance wins: the shorter
variants of one command in the tap are the same sample cut off by the next command.
    speech_blob.py speech_bank.c manifest.json OUT.bin OUT.h
"""
import json, re, sys

def main():
    src, man, out_bin, out_h = sys.argv[1:5]
    t = open(src).read()
    meta = {}
    for m in re.finditer(r'/\* bank (\d+): (\S+) (\d+)ms cmds\[(.*?)\] \*/', t):
        meta[int(m.group(1))] = (m.group(2), int(m.group(3)), re.findall(r"'0x([0-9A-Fa-f]+)'", m.group(4)))
    arrays = {}
    for m in re.finditer(r'static const uint8_t bank_(\d+)\[\][^=]*=\s*\{(.*?)\};', t, re.S):
        arrays[int(m.group(1))] = bytes(int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f]{2})', m.group(2)))
    table = re.search(r'speech_bank\[SPEECH_BANK_COUNT\]\s*=\s*\{(.*?)\};', t, re.S).group(1)
    nib = {int(a): int(b) for a, b in re.findall(r'\{\s*bank_(\d+)\s*,\s*(\d+)\s*\}', table)}
    # command -> bank: from the bank comments (last cmd byte before the utterance), longest ms wins
    best = {}
    for k, (wav, ms, cmds) in meta.items():
        if not cmds: continue
        c = int(cmds[-1], 16)
        if c not in best or ms > best[c][1]: best[c] = (k, ms)
    # only the mapped entries go to the cart (the tap's cut-off duplicates of one command are dropped)
    keep = sorted(set(k for k, _ in best.values()))
    renum = {k: i for i, k in enumerate(keep)}
    best = {c: (renum[k], ms) for c, (k, ms) in best.items()}
    meta = {renum[k]: meta[k] for k in keep}
    n = len(keep)
    blob = bytearray(); ents = []
    for k in keep:
        off = len(blob); blob += arrays[k]
        while len(blob) & 3: blob.append(0)
        ents.append((off, nib[k]))
    open(out_bin, 'wb').write(blob)
    with open(out_h, 'w') as f:
        f.write('/* generated by tools/speech_blob.py: offsets into the speech blob (cart, after the music blob) */\n')
        f.write('#define SPEECH_BANK_COUNT %d\n#define SPEECH_BLOB_LEN %d\n' % (n, len(blob)))
        f.write('struct speech_ent { unsigned int off, nibbles; };\n')
        f.write('static const struct speech_ent speech_tab[%d] = {\n' % n)
        for k, (off, nb) in enumerate(ents):
            wav, ms, cmds = meta.get(k, ('?', 0, []))
            f.write('\t{ %du, %du },   /* %s %dms cmd %s */\n' % (off, nb, wav, ms, cmds[-1] if cmds else '-'))
        f.write('};\n/* sound command byte -> bank entry, 0xFF = none */\nstatic const unsigned char speech_map[256] = {\n')
        for c in range(256):
            f.write('%s0x%02X,%s' % ('\t' if c % 16 == 0 else ' ', best[c][0] if c in best else 0xFF, '\n' if c % 16 == 15 else ''))
        f.write('};\n')
    print('bank', n, 'blob', len(blob), 'bytes; mapped cmds:', ' '.join('%02X->%d' % (c, b[0]) for c, b in sorted(best.items())))

if __name__ == '__main__':
    main()
