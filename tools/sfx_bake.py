#!/usr/bin/env python3
"""Bake the arcade's YM sound effects into the port's PWM SFX bank.
Input: one MAME -wavwrite capture per sound-command byte, made by tools/arcade_wav.lua
(AW_CMD=<hex>, injects the command at frame 200 = 3.333 s with the latch gagged), named
arc_<HEX>.wav. Each is cut from the injection to the end of its activity (+60 ms tail),
mixed to mono, resampled to the mixer rate and IMA-ADPCM encoded with tools/speech_bake.py's
encoder (the matched pair of sh_src/r60/r60_speech.c's decoder). Levels are NOT normalised:
the arcade mix's relative loudness between effects is kept; one linear --gain (default 2.5,
+8 dB, the music lane's own offset over the MAME-arcade absolute) is baked into the bank. Output: a blob and a table header with a 256-entry command map.
    sfx_bake.py WAV_DIR OUT.bin OUT.h [--rate 8000] [--inject 3.333]
The bank rate is 8 kHz (SFX_HOLD 2) because the cart run 0x2FE400-0x340000 is 263 KB: the 61
effects are 436 KB at 16 kHz and 218 KB at 8 kHz (five of them are 2.5-6 s loops/ambients).
"""
import argparse, glob, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from speech_bake import ima_encode, load_wav_16k

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('wav_dir'); ap.add_argument('out_bin'); ap.add_argument('out_h')
    ap.add_argument('--rate', type=int, default=8000)
    ap.add_argument('--inject', type=float, default=200 / 60.0)
    ap.add_argument('--gain', type=float, default=2.5,
                    help='linear gain baked into the bank (default 2.5 = +8 dB): the music lane ships at --gain 6 = ~+7.6 dB '
                         'over MAME-arcade absolute (docs/sound/HANDOFF-SOUND.md), so the effects rise the same amount to keep '
                         'the arcade balance; the ear on the rig sets it from here')
    a = ap.parse_args()
    blob = bytearray(); ents = []; cmap = {}
    for f in sorted(glob.glob(os.path.join(a.wav_dir, 'arc_*.wav'))):
        cmd = int(os.path.basename(f)[4:6], 16)
        s = load_wav_16k(f, a.rate)
        s = s[int(a.inject * a.rate):]
        win = a.rate // 100
        env = [max(abs(x) for x in s[i:i + win]) for i in range(0, len(s) - win, win)]
        pk = max(env) if env else 0
        act = [i for i, e in enumerate(env) if e > max(64, pk // 40)]
        if not act or pk < 100:
            print('%02X: silent (peak %d), skipped' % (cmd, pk)); continue
        end = min(len(s), (act[-1] + 1) * win + a.rate * 6 // 100)
        cut = [max(-32768, min(32767, int(x * a.gain))) for x in s[:end]]
        nib = ima_encode(cut)
        data = bytearray((len(nib) + 1) // 2)
        for i, n in enumerate(nib):
            if i & 1: data[i >> 1] |= n << 4
            else: data[i >> 1] |= n
        off = len(blob); blob += data
        while len(blob) & 3: blob.append(0)
        cmap[cmd] = len(ents); ents.append((off, len(nib), cmd, len(cut) / a.rate, pk))
    open(a.out_bin, 'wb').write(blob)
    with open(a.out_h, 'w') as h:
        h.write('/* generated by tools/sfx_bake.py: the arcade\'s YM effects as IMA ADPCM at %d Hz */\n' % a.rate)
        h.write('#define SFX_BANK_COUNT %d\n#define SFX_BLOB_LEN %d\n#define SFX_HOLD %d   /* 16 kHz mixer samples per nibble */\n' % (len(ents), len(blob), 16000 // a.rate))
        h.write('static const struct speech_ent sfx_tab[%d] = {\n' % len(ents))
        for off, nb, cmd, dur, pk in ents:
            h.write('\t{ %du, %du },   /* cmd %02X %.2fs peak %d */\n' % (off, nb, cmd, dur, pk))
        h.write('};\nstatic const unsigned char sfx_map[256] = {\n')
        for c in range(256):
            h.write('%s0x%02X,%s' % ('\t' if c % 16 == 0 else ' ', cmap.get(c, 0xFF), '\n' if c % 16 == 15 else ''))
        h.write('};\n')
    print('sfx bank: %d effects, %d bytes, longest %.2fs' % (len(ents), len(blob), max(e[3] for e in ents)))

if __name__ == '__main__':
    main()
