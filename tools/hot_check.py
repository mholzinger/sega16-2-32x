#!/usr/bin/env python3
"""POST-LINK CHECK FOR THE HOT SET (PORTHOT2, 2026-10-24). Fails the build when

  1. a function tools/hot_set.txt sends to SDRAM region N is not inside that region in the
     linked elf (an attribute that did not take, a name that was inlined away or renamed,
     a clone left in cart) -- a silently unmoved function reads as a null result;
  2. the object dispatch table (sh_src/portfull/objdispatch.c) differs from the recorded
     baseline in its row count or its keys. 2026-10-13: an attribute written as a prefix
     hid two handlers from cport_dispatch's anchor, they lost their table rows, their
     objects never ran, and the build read as a 21.6% win.

    python3 tools/hot_check.py rom/s16.elf tools/hot_set.txt sh_src/portfull/objdispatch.c \
        tools/hot_dispatch_keys.txt
    ... --update   rewrites the baseline from objdispatch.c (only from a build WITHOUT PORTHOT2)
"""
import os, re, subprocess, sys

NM = os.path.expanduser('~/src/marsdev/mars/sh-elf/bin/sh-elf-nm')


def table_keys(path):
    t = open(path).read()
    rows = re.findall(r'^\s*\{ (0x[0-9A-F]+)u, (\w+) \},', t, re.M)
    n = re.search(r'port_handlers_n = (\d+);', t)
    return rows, int(n.group(1)) if n else -1


def main():
    a = sys.argv[1:]
    update = '--update' in a
    a = [x for x in a if x != '--update']
    elf, hot, disp, base = a
    rows, n = table_keys(disp)
    if update:
        with open(base, 'w') as fh:
            fh.write('# GENERATED by tools/hot_check.py --update: the dispatch table of a build without PORTHOT2\n')
            fh.write('n %d\n' % n)
            fh.writelines('%s %s\n' % r for r in rows)
        print('hot_check: baseline %d rows -> %s' % (n, base))
        return 0
    bad = []
    want = [l.split() for l in open(base) if l.strip() and not l.startswith('#')]
    bn = int(want[0][1]); brows = [tuple(x) for x in want[1:]]
    if n != bn or len(rows) != n:
        bad.append('dispatch table has %d rows (port_handlers_n %d), baseline %d' % (len(rows), n, bn))
    elif rows != brows:
        diff = [(x, y) for x, y in zip(rows, brows) if x != y][:5]
        bad.append('dispatch table keys differ from the baseline: %s' % diff)
    syms = {}
    for line in subprocess.run([NM, '-S', elf], capture_output=True, text=True, check=True).stdout.splitlines():
        f = line.split()
        if len(f) == 4:
            syms.setdefault(f[3], []).append((int(f[0], 16), int(f[1], 16)))
        elif len(f) == 3:
            syms.setdefault(f[2], []).append((int(f[0], 16), 0))
    reg = {}
    for r in ('2', '3'):
        s = syms.get('___ramtext%s_start' % r) or syms.get('__ramtext%s_start' % r)
        e = syms.get('___ramtext%s_end' % r) or syms.get('__ramtext%s_end' % r)
        if s and e:
            reg[r] = (s[0][0], e[0][0])
    moved = 0
    for l in open(hot):
        if not l.strip() or l.startswith('#'):
            continue
        name, r = l.split()[0].split('@')
        if r not in reg:
            bad.append('%s@%s: region %s is not linked' % (name, r, r)); continue
        lo, hi = reg[r]
        hits = [(k, v) for k, vs in syms.items() for v in vs
                if re.fullmatch(r'_%s(\.\w+(\.\d+)?)*' % re.escape(name), k)]
        if not hits:
            bad.append('%s@%s: no symbol in the elf (inlined away or renamed)' % (name, r)); continue
        out = [(k, hex(v[0])) for k, v in hits if not (lo <= v[0] < hi)]
        if out:
            bad.append('%s@%s: outside [%#x,%#x): %s' % (name, r, lo, hi, out))
        else:
            moved += 1
    if bad:
        print('hot_check: FAIL\n  ' + '\n  '.join(bad))
        return 1
    print('hot_check: %d hot functions in place (%s); dispatch table %d rows = baseline'
          % (moved, ', '.join('region %s %#x-%#x %d B' % (r, lo, hi, hi - lo) for r, (lo, hi) in sorted(reg.items())), n))
    return 0


if __name__ == '__main__':
    sys.exit(main())
